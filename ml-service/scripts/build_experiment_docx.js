// ── อ่านขนาดจริงจาก PNG header (IHDR อยู่ที่ byte 16–24) ──
function pngSize(file) {
  const b = fs.readFileSync(file);
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
}

