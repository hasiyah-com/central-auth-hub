function Tbl(headers, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cols = widths.map((x) => Math.round((x / total) * TABLE_W));
  const cell = (text, o = {}) =>
    new TableCell({
      width: { size: cols[o.i], type: WidthType.DXA },
      shading: o.headRow
        ? { type: ShadingType.CLEAR, fill: C.head }
        : o.zebra ? { type: ShadingType.CLEAR, fill: "F5F6FA" } : undefined,
      margins: { top: 70, bottom: 70, left: 110, right: 110 },
      children: [new Paragraph({
        alignment: o.i === 0 ? AlignmentType.LEFT : AlignmentType.CENTER,
        spacing: { after: 0, line: 340 },
        children: [new TextRun({
          text: String(text), font: o.mono ? MONO : FONT, size: o.mono ? 24 : 29,
          bold: o.headRow || o.bold,
          color: o.headRow ? "FFFFFF" : (o.color ?? "1A1A1A"),
        })],
      })],
    });
  return new Table({
    columnWidths: cols,
    width: { size: TABLE_W, type: WidthType.DXA },
    rows: [
      new TableRow({
        tableHeader: true,
        children: headers.map((t, i) => cell(t, { i, headRow: true })),
      }),
      ...rows.map((r, ri) => new TableRow({
        children: r.map((t, i) => {
          let s = String(t);
          const bold = s.startsWith("*");
          if (bold) s = s.slice(1);
          let color;
          if (s.startsWith("+")) { color = C.good; s = s.slice(1); }
          else if (s.startsWith("-")) { color = C.bad; s = s.slice(1); }
          return cell(s, { i, zebra: ri % 2 === 1, bold, color });
        }),
      })),
    ],
  });
}

