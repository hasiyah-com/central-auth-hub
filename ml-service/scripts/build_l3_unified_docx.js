function Figure(fileName, caption) {
  const p = path.join(CHARTS, fileName);
  const { w, h } = pngSize(p);
  const width = Math.min(CONTENT_W, w);
  return [
    new Paragraph({
      alignment: AlignmentType.CENTER, spacing: { before: 160, after: 60 },
      children: [new ImageRun({ type: "png", data: fs.readFileSync(p),
                                transformation: { width, height: Math.round(h * (width / w)) } })],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER, spacing: { after: 200 },
      children: [new TextRun({ text: caption, font: FONT, size: 27,
                               italics: true, color: C.cap })],
    }),
  ];
}

function Tbl(headers, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cols = widths.map((x) => Math.round((x / total) * TABLE_W));
  const cell = (text, o = {}) =>
    new TableCell({
      width: { size: cols[o.i], type: WidthType.DXA },
      shading: o.headRow ? { type: ShadingType.CLEAR, fill: C.head }
                         : o.zebra ? { type: ShadingType.CLEAR, fill: "F5F6FA" } : undefined,
      margins: { top: 70, bottom: 70, left: 110, right: 110 },
      children: [new Paragraph({
        alignment: o.i === 0 ? AlignmentType.LEFT : AlignmentType.CENTER,
        spacing: { after: 0, line: 340 },
        children: [new TextRun({ text: String(text), font: FONT, size: 29,
                                 bold: o.headRow || o.bold,
                                 color: o.headRow ? "FFFFFF" : (o.color ?? "1A1A1A") })],
      })],
    });
  return new Table({
    columnWidths: cols,
    width: { size: TABLE_W, type: WidthType.DXA },
    rows: [
      new TableRow({ tableHeader: true,
        children: headers.map((t, i) => cell(t, { i, headRow: true })) }),
      ...rows.map((r, ri) => new TableRow({
        children: r.map((t, i) => {
          const s = String(t);
          const bold = s.startsWith("*");
          return cell(bold ? s.slice(1) : s, { i, zebra: ri % 2 === 1, bold });
        }),
      })),
    ],
  });
}

